def normalize_language(language: str | None) -> str:
    if language in SUPPORTED_LANGUAGES:
        return language
    return "en"


def get_language(request: Request | None) -> str:
    if request is None:
        return "en"
    return normalize_language(request.cookies.get(LANGUAGE_COOKIE))


def build_language_response(language: str, next_url: str | None) -> RedirectResponse:
    if not next_url or not next_url.startswith("/") or next_url.startswith("//"):
        next_url = "/"
    response = RedirectResponse(next_url or "/", status_code=303)
    response.set_cookie(
        LANGUAGE_COOKIE,
        normalize_language(language),
        max_age=60 * 60 * 24 * 365,
        samesite="lax",
    )
    return response


@pass_context
def current_language(context) -> str:
    return get_language(context.get("request"))


@pass_context
def language_url(context, language: str) -> str:
    request = context.get("request")
    next_url = str(request.url.path) if request else "/"
    if request and request.url.query:
        next_url = f"{next_url}?{request.url.query}"
    return f"/language/{normalize_language(language)}?next={quote(next_url, safe='')}"


@pass_context
def translations(context) -> dict[str, str]:
    if current_language(context) == "ru":
        return RU_TRANSLATIONS
    return {}


@pass_context
def translate(context, text: str) -> str:
    if current_language(context) == "ru":
        if text.startswith("Indexed ") and text.endswith(" semantic chunk(s)."):
            count = text.removeprefix("Indexed ").removesuffix(" semantic chunk(s).")
            return f"Проиндексировано семантических фрагментов: {count}."
        if text.startswith("Processed and indexed ") and " semantic chunk(s)." in text:
            count = text.removeprefix("Processed and indexed ").split(" semantic chunk(s).", 1)[0]
            return f"Обработано и проиндексировано семантических фрагментов: {count}."
        if text.startswith("What does the document say about ") and text.endswith("?"):
            topic = text.removeprefix("What does the document say about ").removesuffix("?")
            return f"Что документ говорит о {topic}?"
        if text.startswith("Due in ") and text.endswith(" day(s)"):
            days = text.removeprefix("Due in ").removesuffix(" day(s)")
            return f"через {days} дн."
        if text.endswith(" day(s) overdue"):
            days = text.removesuffix(" day(s) overdue")
            return f"просрочено на {days} дн."
        return RU_TRANSLATIONS.get(text, text)
    return text
